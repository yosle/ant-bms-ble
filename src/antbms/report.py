"""Build a full, human-readable report of a BMS: identity, settings, state.

Pure functions over already-received data, so everything here is testable
without hardware. The CLI gathers the frames over BLE and hands them in.
"""

import json
import time

from .params import PARAM_BLOCKS, PARAM_MAP, PARAM_META


def decode_block_values(block_name, payload):
    """Turn a parameter-block payload into a list of named entries."""
    addr0 = PARAM_BLOCKS[block_name]["addr"]
    entries = []
    for i in range(0, len(payload) - 1, 2):
        addr = addr0 + i
        raw = payload[i] | (payload[i + 1] << 8)
        info = PARAM_MAP.get(addr)
        meta = PARAM_META.get(addr, {})
        name = info[0] if info else "addr_%d" % addr
        entry = {
            "addr": addr,
            "name": name,
            "raw": raw,
            "unit": meta.get("unit", ""),
        }
        if raw == 0xFFFF:
            entry["value"] = None  # parameter not configured on the BMS
        elif info:
            _, itimes, dec = info
            entry["value"] = round(raw / float(itimes), dec)
        else:
            entry["value"] = raw
        entries.append(entry)
    return entries


def build_report(device, blocks, snapshot, *, version="", now=None):
    """Assemble the report dict.

    device:   {"hardware": str, "software": str, "pack_id": str, ...}
    blocks:   {block_name: payload_bytes}
    snapshot: decoded real-time dict (or None)
    """
    report = {
        "tool": "ant-bms-ble %s" % version if version else "ant-bms-ble",
        "generated": time.strftime("%Y-%m-%d %H:%M:%S",
                                   time.localtime(now if now is not None else time.time())),
        "device": dict(device),
        "settings": {
            name: decode_block_values(name, payload)
            for name, payload in blocks.items()
        },
        "realtime": dict(snapshot) if snapshot else None,
    }
    return report


def to_json(report):
    return json.dumps(report, indent=2, ensure_ascii=False)


def _fmt_value(entry):
    if entry["value"] is None:
        return "not configured"
    unit = (" " + entry["unit"]) if entry["unit"] else ""
    return "%s%s" % (entry["value"], unit)


def to_markdown(report):
    lines = ["# ANT BMS report", ""]
    lines.append("Generated by %s on %s" % (report["tool"], report["generated"]))
    lines.append("")
    if report["device"]:
        lines.append("## Device")
        lines.append("")
        for key, value in report["device"].items():
            lines.append("- **%s**: %s" % (key.replace("_", " "), value))
        lines.append("")
    snap = report.get("realtime")
    if snap:
        lines.append("## Real-time snapshot")
        lines.append("")
        lines.append("- **state**: %s" % snap["systemStateName"])
        lines.append("- **pack**: %.2f V, %.2f A, %d W" %
                     (snap["packVoltage"], snap["current"], snap["packPower"]))
        lines.append("- **SOC / SOH**: %d%% / %d%%" % (snap["soc"], snap["soh"]))
        lines.append("- **cells**: %d (min %.3f V #%d, max %.3f V #%d, diff %.0f mV)" %
                     (snap["cellCount"], snap["cellVoltageMin"], snap["cellVoltageMinPos"],
                      snap["cellVoltageMax"], snap["cellVoltageMaxPos"],
                      snap["cellVoltageDiff"] * 1000))
        lines.append("- **capacity**: %.1f / %.1f Ah" %
                     (snap["packRemainAh"], snap["packPhysicsAh"]))
        if snap["protections"]:
            lines.append("- **PROTECTIONS**: " + ", ".join(snap["protections"]))
        if snap["warnings"]:
            lines.append("- **warnings**: " + ", ".join(snap["warnings"]))
        lines.append("")
    for block, entries in report["settings"].items():
        lines.append("## Settings — %s" % block)
        lines.append("")
        lines.append("| addr | parameter | value | raw |")
        lines.append("|---:|---|---|---:|")
        for e in entries:
            lines.append("| %d | %s | %s | 0x%04X |" %
                         (e["addr"], e["name"], _fmt_value(e), e["raw"]))
        lines.append("")
    return "\n".join(lines)
